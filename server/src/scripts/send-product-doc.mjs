import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import nodemailer from 'nodemailer';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const envPath = path.resolve(__dirname, '../../.env');

if (fs.existsSync(envPath)) {
  for (const line of fs.readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith('#') || !t.includes('=')) continue;
    const idx = t.indexOf('=');
    const k = t.slice(0, idx).trim();
    const v = t.slice(idx + 1).trim().replace(/^["']|["']$/g, '');
    if (!(k in process.env)) process.env[k] = v;
  }
}

const docPath = path.resolve(__dirname, '../../../NOVAQI_PRODUCT_DOCUMENT.md');
const docContent = fs.readFileSync(docPath, 'utf8');

const transport = nodemailer.createTransport({
  host: process.env.SMTP_HOST,
  port: Number(process.env.SMTP_PORT || 465),
  secure: process.env.SMTP_SECURE === 'true',
  auth: { user: process.env.SMTP_USER, pass: process.env.SMTP_PASS },
});

const mdToHtml = (md) => {
  return md
    .replace(/^### (.+)$/gm, '<h3 style="color:#0E1B14;margin-top:24px;margin-bottom:8px">$1</h3>')
    .replace(/^## (.+)$/gm, '<h2 style="color:#0E1B14;border-bottom:2px solid #16A75A;padding-bottom:6px;margin-top:32px">$1</h2>')
    .replace(/^# (.+)$/gm, '<h1 style="color:#0E1B14;font-size:24px">$1</h1>')
    .replace(/^\*\*(.+?)\*\*$/gm, '<strong>$1</strong>')
    .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
    .replace(/^> (.+)$/gm, '<blockquote style="border-left:4px solid #16A75A;padding:12px 16px;background:#f0f9ee;color:#333;margin:16px 0;font-style:italic">$1</blockquote>')
    .replace(/^---$/gm, '<hr style="border:none;border-top:1px solid #ddd;margin:24px 0">')
    .replace(/^- (.+)$/gm, '<li style="margin:4px 0">$1</li>')
    .replace(/(<li[^>]*>.*<\/li>\n?)+/gs, (m) => `<ul style="padding-left:20px;margin:8px 0">${m}</ul>`)
    .replace(/\n\n/g, '</p><p style="margin:8px 0;color:#333;font-size:14px">')
    .replace(/^(?!<[hublp])(.+)$/gm, (m) => m.trim() ? m : '');
};

const html = `
<div style="font-family:sans-serif;max-width:800px;margin:0 auto;padding:32px;background:#fff;">
  <div style="background:#0E1B14;padding:20px 28px;border-radius:12px;margin-bottom:32px">
    <span style="color:#16A75A;font-size:22px;font-weight:800">Nova</span><span style="color:#E8991C;font-size:22px;font-weight:800">QI</span>
    <span style="color:#aaa;font-size:13px;margin-left:16px">Product Document — 2026-08-14</span>
  </div>
  <div style="font-size:14px;color:#333;line-height:1.6">
    ${mdToHtml(docContent)}
  </div>
  <hr style="border:none;border-top:1px solid #eee;margin:32px 0">
  <p style="color:#999;font-size:11px">Generated by Claude Code · NovaQI internal document</p>
</div>
`;

await transport.sendMail({
  from: process.env.SMTP_FROM || 'NovaQI <contact@veganland.app>',
  to: 'daviwazlawick@gmail.com',
  subject: 'NovaQI — Complete Product Document (manual + ads)',
  html,
  attachments: [
    {
      filename: 'NOVAQI_PRODUCT_DOCUMENT.md',
      content: docContent,
      contentType: 'text/markdown',
    },
  ],
});

console.log('Email sent to daviwazlawick@gmail.com');
